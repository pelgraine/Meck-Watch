#!/usr/bin/env python3
"""bake_watch_emoji.py -- bake Twemoji 72x72 PNGs to 10x10 RGB332 for the
Meck Watch, emitting examples/companion_radio/ui-new/WatchEmojiData.h.

Pipeline per emoji (identical to the seedling proof):
  Lanczos 72->10, composite alpha onto black (the watch background) so
  semi-transparent edges don't grey out, alpha < 50% -> colour key 0xE3.

Usage: bake_watch_emoji.py <registry.txt> <twemoji 72x72 dir> <out .h>
"""
import sys, re
from PIL import Image

W = H = 10
KEY = 0xE3   # RGB332 magenta -- never produced for an opaque pixel

def to332(r, g, b):
    return ((r >> 5) << 5) | ((g >> 5) << 2) | (b >> 6)

def bake(path):
    im = Image.open(path).convert('RGBA').resize((W, H), Image.LANCZOS)
    out = []
    for y in range(H):
        for x in range(W):
            r, g, b, a = im.getpixel((x, y))
            if a < 128:
                out.append(KEY)
                continue
            r = r * a // 255; g = g * a // 255; b = b * a // 255
            v = to332(r, g, b)
            if v == KEY: v = 0xE2   # nudge an accidental key hit
            out.append(v)
    return out

def main():
    reg, assets, outp = sys.argv[1:4]
    entries = []
    seen_seq = set()
    for ln in open(reg):
        ln = ln.split('#', 1)[0].strip()
        if not ln: continue
        name, seq = ln.split()
        cps = [int(c, 16) for c in seq.split('-') if c != 'fe0f']
        if tuple(cps) in seen_seq:
            print(f"skip duplicate sequence {seq} ({name})", file=sys.stderr)
            continue
        seen_seq.add(tuple(cps))
        # Twemoji file naming: full sequence including fe0f only for ZWJ seqs
        fname = seq if '200d' in seq else '-'.join(c for c in seq.split('-') if c != 'fe0f')
        path = f"{assets}/{fname}.png"
        try:
            px = bake(path)
        except FileNotFoundError:
            print(f"MISSING asset for {name}: {path}", file=sys.stderr)
            continue
        entries.append((name, cps, px))

    with open(outp, 'w') as f:
        f.write("// WatchEmojiData.h -- GENERATED by tools/bake_watch_emoji.py. Do not edit.\n")
        f.write("// Twemoji (jdecked) baked to 10x10 RGB332 for the T-Watch LCD.\n")
        f.write("// Graphics (c) Twitter/Twemoji contributors, CC BY 4.0.\n")
        f.write(f"// {len(entries)} emoji, {len(entries) * W * H} bytes of pixel data.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        for name, cps, px in entries:
            f.write(f"static const uint8_t wemoji_{name}[{W*H}] = {{\n")
            for y in range(H):
                f.write("  " + ",".join(f"0x{v:02X}" for v in px[y*W:(y+1)*W]) + ",\n")
            f.write("};\n")
        f.write("\n// Sequence table. cp[0..n-1] is the codepoint sequence (fe0f excluded);\n")
        f.write("// n is its length. Multi-codepoint entries (flags, ZWJ) must precede any\n")
        f.write("// single-codepoint entry sharing their first codepoint so the longest\n")
        f.write("// match wins -- the generator sorts by descending length.\n")
        f.write("#define WEMOJI_SEQ_MAX 4\n")
        f.write("struct WatchEmoji { uint32_t cp[WEMOJI_SEQ_MAX]; uint8_t n; const uint8_t* px; };\n")
        f.write("static const WatchEmoji WATCH_EMOJI[] = {\n")
        for name, cps, px in sorted(entries, key=lambda e: -len(e[1])):
            cpl = ",".join(f"0x{c:X}" for c in cps) + ("," + ",".join("0"*(4-len(cps))) if len(cps) < 4 else "")
            f.write(f"  {{ {{{cpl}}}, {len(cps)}, wemoji_{name} }},\n")
        f.write("};\n")
        f.write("#define WATCH_EMOJI_COUNT ((int)(sizeof(WATCH_EMOJI) / sizeof(WATCH_EMOJI[0])))\n")
    print(f"wrote {outp}: {len(entries)} emoji", file=sys.stderr)

if __name__ == '__main__':
    main()
